import { test, expect, chromium } from '@playwright/test';
import { mkdtemp, rm } from 'node:fs/promises';
import { resolve, dirname, basename } from 'node:path';
import { tmpdir } from 'node:os';

test('categorized selection adds once, persists, handles failures and fits mobile', async () => {
  const profile = await mkdtemp(resolve(tmpdir(), 'taiwan-catalog-test-'));
  const extension = resolve('dist');
  const context = await chromium.launchPersistentContext(profile, {
    channel: 'chromium', headless: true, viewport: { width: 1280, height: 900 },
    args: [`--disable-extensions-except=${extension}`, `--load-extension=${extension}`],
  });
  try {
    await context.setOffline(true);
    const page = await context.newPage(); await page.goto('chrome://newtab/');
    const open = page.getByRole('button', { name: '常用網站', exact: true });
    const dialog = page.getByRole('dialog', { name: '常用網站', exact: true });
    const categories = dialog.getByRole('group', { name: '網站分類', exact: true });
    await expect(open).toBeEnabled();
    const center = await open.locator('.shortcut-icon').evaluate(element => {
      const outer = element.getBoundingClientRect(), inner = element.querySelector('svg')!.getBoundingClientRect();
      return { x: Math.abs(inner.x + inner.width / 2 - outer.x - outer.width / 2), y: Math.abs(inner.y + inner.height / 2 - outer.y - outer.height / 2) };
    });
    expect(center.x).toBeLessThan(1); expect(center.y).toBeLessThan(1);
    await open.click();
    await expect(dialog.locator('.catalog-site')).toHaveCount(52);
    const logos = dialog.locator('.catalog-site-symbol img');
    await expect(logos).toHaveCount(52);
    await expect.poll(() => logos.evaluateAll(images => images.every(image =>
      (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true);
    await expect(dialog.locator('input[value=youtube]')).toBeChecked();
    await expect(dialog.locator('input[value=youtube]')).toBeEnabled();
    for (const id of ['yahoo', 'youtube', 'chatgpt', 'gemini', 'google']) {
      await expect(dialog.locator(`input[value=${id}]`)).toBeChecked();
    }
    await expect(dialog.locator('#website-catalog-add')).toBeDisabled();
    await categories.getByRole('button', { name: '購物與生活', exact: true }).click();
    await expect(dialog.locator('.catalog-site').first()).toContainText('蝦皮購物');
    await categories.getByRole('button', { name: 'AI 工具', exact: true }).click();
    await expect(dialog.locator('input[value=napkin]')).toBeVisible();
    await categories.getByRole('button', { name: '工作與學習', exact: true }).click();
    await expect(dialog.locator('input[value=apps-script]')).toBeVisible();
    await categories.getByRole('button', { name: '搜尋與入口', exact: true }).click();
    await dialog.locator('input[value=duckduckgo]').check();
    await dialog.getByRole('button', { name: '還原變更', exact: true }).click();
    await expect(dialog.locator('input[value=duckduckgo]')).not.toBeChecked();
    await expect(dialog.locator('#website-catalog-add')).toBeDisabled();
    await dialog.locator('input[value=duckduckgo]').check();
    await categories.getByRole('button', { name: '工作與學習', exact: true }).click();
    await dialog.locator('input[value=gmail]').check();
    await categories.getByRole('button', { name: 'AI 工具', exact: true }).click();
    await dialog.locator('input[value=claude]').check();
    await expect(dialog.locator('#website-catalog-count')).toHaveText('已選 3 個網站');
    await categories.getByRole('button', { name: '搜尋與入口', exact: true }).click();
    await expect(dialog.locator('input[value=duckduckgo]')).toBeChecked();
    await dialog.getByRole('button', { name: '新增 3 個捷徑', exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await expect(page.locator('.shortcut-name')).toHaveText(['Yahoo 奇摩', 'YouTube', 'ChatGPT', 'Gemini', 'Google', 'DuckDuckGo', 'Claude', 'Gmail']);
    await page.reload();
    await expect(page.getByRole('link', { name: 'Claude', exact: true })).toHaveAttribute('href', 'https://claude.ai/');
    await expect(page.getByRole('link', { name: 'Claude', exact: true }).locator('img')).toHaveAttribute('src', './icons/websites/claude.ico');
    await open.click();
    await expect(dialog.locator('input[value=google]')).toBeEnabled();
    const search = dialog.getByRole('searchbox', { name: '搜尋常用網站' });
    await search.fill('台灣高鐵');
    await expect(dialog.locator('.catalog-site')).toHaveCount(1);
    await dialog.locator('input[value=thsrc]').check();
    await search.fill('no-matching-site');
    await expect(dialog.locator('.catalog-empty')).toBeVisible();
    await expect(dialog.locator('#website-catalog-count')).toHaveText('已選 1 個網站');
    await page.keyboard.press('Escape'); await open.click();
    await expect(dialog.locator('#website-catalog-count')).toHaveText('已選 0 個網站');
    expect(await dialog.locator('#website-catalog-list').evaluate(element => element.scrollTop)).toBe(0);
    await dialog.locator('input[value=thsrc]').check();
    await page.evaluate(() => {
      const original = chrome.storage.local.set.bind(chrome.storage.local);
      (window as any).restoreCatalogStorage = () => { chrome.storage.local.set = original; };
      chrome.storage.local.set = (async () => { throw new Error('quota'); }) as typeof chrome.storage.local.set;
    });
    await dialog.getByRole('button', { name: '新增 1 個捷徑', exact: true }).click();
    await expect(dialog.locator('#website-catalog-error')).toContainText('無法儲存');
    await expect(dialog.locator('input[value=thsrc]')).toBeChecked();
    await expect(page.getByRole('link', { name: '台灣高鐵', exact: true })).toHaveCount(0);
    await page.evaluate(() => (window as any).restoreCatalogStorage());
    const other = await context.newPage(); await other.goto(page.url());
    await dialog.getByRole('button', { name: '新增 1 個捷徑', exact: true }).click();
    await expect(other.getByRole('link', { name: '台灣高鐵', exact: true })).toBeVisible();
    await open.click();
    await categories.getByRole('button', { name: '搜尋與入口', exact: true }).click();
    await dialog.locator('input[value=yahoo]').uncheck();
    await expect(dialog.locator('#website-catalog-count')).toHaveText('新增 0 個・移除 1 個');
    await expect(dialog.locator('.catalog-site-removing')).toContainText('將移除');
    await dialog.getByRole('button', { name: '取消', exact: true }).click();
    await expect(page.getByRole('link', { name: 'Yahoo 奇摩', exact: true })).toBeVisible();
    await open.click();
    await expect(dialog.locator('input[value=yahoo]')).toBeChecked();
    await dialog.locator('input[value=yahoo]').uncheck();
    await dialog.getByRole('button', { name: '還原變更', exact: true }).click();
    await expect(dialog.locator('input[value=yahoo]')).toBeChecked();
    await expect(dialog.locator('#website-catalog-add')).toBeDisabled();
    await dialog.locator('input[value=yahoo]').uncheck();
    await dialog.locator('input[value=bing]').check();
    await categories.getByRole('button', { name: 'AI 工具', exact: true }).click();
    await expect(dialog.locator('#website-catalog-count')).toHaveText('新增 1 個・移除 1 個');
    await page.evaluate(() => {
      const original = chrome.storage.local.set.bind(chrome.storage.local);
      (window as any).restoreCatalogStorage = () => { chrome.storage.local.set = original; };
      chrome.storage.local.set = (async () => { throw new Error('quota'); }) as typeof chrome.storage.local.set;
    });
    await dialog.getByRole('button', { name: '儲存變更', exact: true }).click();
    await expect(dialog.locator('#website-catalog-error')).toContainText('無法儲存');
    await expect(other.getByRole('link', { name: 'Yahoo 奇摩', exact: true })).toBeVisible();
    await expect(other.getByRole('link', { name: 'Bing', exact: true })).toHaveCount(0);
    await categories.getByRole('button', { name: '搜尋與入口', exact: true }).click();
    await expect(dialog.locator('input[value=yahoo]')).not.toBeChecked();
    await expect(dialog.locator('input[value=bing]')).toBeChecked();
    await page.evaluate(() => (window as any).restoreCatalogStorage());
    await dialog.getByRole('button', { name: '儲存變更', exact: true }).click();
    await expect(other.getByRole('link', { name: 'Yahoo 奇摩', exact: true })).toHaveCount(0);
    await expect(other.getByRole('link', { name: 'Bing', exact: true })).toBeVisible();
    await page.reload();
    await expect(page.getByRole('link', { name: 'Yahoo 奇摩', exact: true })).toHaveCount(0);
    await expect(page.getByRole('link', { name: 'Bing', exact: true })).toBeVisible();
    await page.setViewportSize({ width: 360, height: 800 });
    await open.click();
    await expect(dialog).toBeVisible();
    expect(await dialog.locator('#website-catalog-list').evaluate(element => element.scrollTop)).toBe(0);
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    await expect(dialog.locator('#website-catalog-list')).toHaveCSS('grid-template-columns', /^(?!.* .*).+$/);
    await page.screenshot({ path: 'test-results/website-catalog-mobile.png', fullPage: true });
    await page.keyboard.press('Escape');
    await page.setViewportSize({ width: 1280, height: 900 }); await open.click();
    await page.evaluate(() => { document.documentElement.dataset.style = 'classic'; });
    await page.screenshot({ path: 'test-results/website-catalog-desktop.png', fullPage: true, animations: 'disabled' });
    await page.evaluate(() => { document.documentElement.classList.add('dark'); });
    await expect(categories.getByRole('button', { name: '搜尋與入口', exact: true })).toHaveCSS('background-color', 'rgb(42, 46, 49)');
    await page.screenshot({ path: 'test-results/website-catalog-dark.png', fullPage: true, animations: 'disabled' });
    await dialog.getByRole('button', { name: '取消', exact: true }).click();
    await page.getByRole('button', { name: '編輯 Gemini', exact: true }).click();
    await page.locator('#shortcut-name').fill('我的 Gemini');
    await page.locator('#shortcut-url').fill('https://gemini.google.com/u/0/app?hl=zh-TW');
    await page.getByRole('button', { name: '完成', exact: true }).click();
    await expect(page.locator('#shortcut-dialog')).not.toBeVisible();
    await open.click();
    await categories.getByRole('button', { name: 'AI 工具', exact: true }).click();
    await expect(dialog.locator('input[value=gemini]')).toBeChecked();
    await expect(dialog.locator('input[value=gemini]')).toBeEnabled();
    await expect(dialog.locator('#website-catalog-add')).toBeDisabled();
    await dialog.locator('input[value=napkin]').check();
    await dialog.getByRole('button', { name: '新增 1 個捷徑', exact: true }).click();
    await expect(page.locator('#shortcuts a[href^="https://gemini.google.com/"]')).toHaveCount(1);
    await expect(page.getByRole('link', { name: '我的 Gemini', exact: true })).toHaveAttribute('href', 'https://gemini.google.com/u/0/app?hl=zh-TW');
    await page.reload();
    await expect(page.locator('#shortcuts a[href^="https://gemini.google.com/"]')).toHaveCount(1);
  } finally {
    await context.close();
    if (dirname(resolve(profile)) !== resolve(tmpdir()) || !basename(profile).startsWith('taiwan-catalog-test-')) throw new Error('Unexpected profile path');
    await rm(profile, { recursive: true, force: true });
  }
});
